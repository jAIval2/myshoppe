from typing import Protocol
from .schemas import Save, Action
from app.identity import Actor


class Bespoke(Protocol):
    def list(self, actor: Actor, admin: bool = False) -> list[dict]: ...
    def get(self, actor: Actor, design_id: str, admin: bool = False) -> dict: ...
    def create(self, actor: Actor) -> dict: ...
    def save(self, actor: Actor, design_id: str, command: Save) -> dict: ...
    def action(self, actor: Actor, design_id: str, command: Action, admin: bool = False) -> dict: ...
    def upload(self, actor: Actor, design_id: str, data: bytes, kind: str) -> dict: ...
    def asset(self, actor: Actor, asset_id: str) -> dict: ...
